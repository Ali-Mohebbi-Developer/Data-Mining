from pathlib import Path

import pandas as pd


def render_table(dataframe: pd.DataFrame, rows: int = 10) -> str:
    if dataframe.empty:
        return "نتیجه‌ای تولید نشد."
    return dataframe.head(rows).round(4).to_markdown(index=False)


def build_report(dataframe: pd.DataFrame, rules: pd.DataFrame, classification_metrics: pd.DataFrame, clustering_metrics: pd.DataFrame, output_path: Path) -> None:
    content = f"""# گزارش اجرای پروژه داده‌کاوی محصولات فروشگاهی

## ۱. معرفی مسئله و دلیل انتخاب موضوع

موضوع پروژه تحلیل محصولات یک فروشگاه آزمایشی کتاب است. منبع اصلی، وب‌سایت عمومی Books to Scrape است که برای تمرین وب‌اسکرپینگ ساخته شده و شامل نزدیک به هزار محصول است. هدف، ساخت یک خط لوله کامل از جمع‌آوری و پاک‌سازی داده تا قواعد انجمنی، دسته‌بندی و خوشه‌بندی است.

## ۲. منبع داده و روش جمع‌آوری

داده خام همراه پروژه شامل {len(dataframe)} رکورد است. ماژول `src/web_scraper.py` صفحات فهرست و صفحه جزئیات هر محصول را پیمایش می‌کند. برای اجرای آفلاین و قابل تکرار، یک نسخه خام در `data/raw/books_seed.csv` قرار دارد.

## ۳. ساخت دیتاست و ستون‌ها

دیتاست پردازش‌شده {dataframe.shape[0]} رکورد و {dataframe.shape[1]} ستون دارد. ستون‌های اصلی شامل عنوان، قیمت، امتیاز، موجودی، نشانی محصول و تصویر است. ستون‌های مهندسی‌شده شامل تعداد واژه‌های عنوان، طول متن، گروه قیمت، موضوع عنوان، وجود عدد سری و نسبت واژه‌های یکتا است.

## ۴. پاک‌سازی داده و چالش‌ها

رکوردهای تکراری بر اساس عنوان و نشانی حذف شدند. قیمت‌ها به عدد اعشاری تبدیل شدند. امتیازهای گمشده با نما جایگزین شدند. وضعیت موجودی یکسان‌سازی شد. متن‌ها از فاصله‌های اضافی پاک شدند. در نسخه خام ذخیره‌شده، شرح کامل و دسته محصول موجود نبود، بنابراین عنوان به‌عنوان متن پایه استفاده شد و اسکرپر کامل امکان بازیابی این فیلدها را دارد.

## ۵. تحلیل آماری اولیه

میانگین قیمت برابر با {dataframe['price'].mean():.2f} پوند و میانه قیمت برابر با {dataframe['price'].median():.2f} پوند است. میانگین امتیاز عددی {dataframe['rating_numeric'].mean():.2f} از ۵ است. نمودارهای توزیع قیمت، فراوانی امتیاز و قیمت بر حسب امتیاز در پوشه `reports/figures` ذخیره شده‌اند.

## ۶. مهندسی ویژگی

برای متن از TF-IDF یک‌واژه‌ای و دوواژه‌ای استفاده شد. ویژگی‌های عددی شامل قیمت، امتیاز عددی، تعداد واژه‌های عنوان، تعداد نویسه‌های عنوان، تعداد واژه‌های توضیح و نسبت واژه‌های یکتا هستند. ویژگی‌های دسته‌ای شامل گروه قیمت، گروه امتیاز، موضوع متن، گروه حرف اول و وجود عدد در عنوان هستند.

## ۷. نتایج قواعد انجمنی

حداقل ۱۵ قانون از سبد ویژگی‌های هر محصول استخراج شد. جدول زیر ده قانون برتر را بر اساس Lift نشان می‌دهد.

{render_table(rules, 10)}

Support سهم رکوردهای شامل هر دو سمت قانون است. Confidence احتمال مشاهده نتیجه در صورت وجود مقدمه است. Lift بزرگ‌تر از یک نشان می‌دهد هم‌زمانی دو سمت بیشتر از حالت استقلال است. قوانین این پروژه الگوهای توصیفی دیتاست هستند و رابطه علت و معلولی را اثبات نمی‌کنند.

## ۸. نتایج دسته‌بندی

برچسب دسته‌بندی، گروه قیمت سه‌سطحی است. داده با نسبت ۷۵ به ۲۵ و به‌صورت طبقه‌بندی‌شده به آموزش و آزمون تقسیم شد. دو مدل رگرسیون لجستیک و جنگل تصادفی اجرا شدند.

{render_table(classification_metrics, 10)}

## ۹. نتایج خوشه‌بندی

برای تعیین تعداد خوشه‌ها، مقدار Silhouette برای k از ۲ تا ۶ محاسبه شد. سپس KMeans و Agglomerative با بهترین k اجرا شدند.

{render_table(clustering_metrics, 10)}

پروفایل هر خوشه در فایل‌های `cluster_profiles_kmeans.csv` و `cluster_profiles_agglomerative.csv` قرار دارد و شامل اندازه خوشه، میانگین قیمت، میانگین امتیاز و موضوع غالب است.

## ۱۰. جمع‌بندی و پیشنهاد کار آینده

خط لوله پروژه تمام فازهای اصلی را پوشش می‌دهد. مهم‌ترین محدودیت نسخه همراه پروژه، کمبود دسته و شرح کامل محصول در فایل خام ذخیره‌شده است. اجرای گزینه `--scrape` این فیلدها را مستقیماً از صفحات عمومی بازیابی می‌کند. در کار آینده می‌توان مدل‌های قوی‌تر متنی، کاهش بعد متفاوت و تحلیل پایداری خوشه‌ها را بررسی کرد.

## ۱۱. راهنمای اجرای کد

دستور اصلی اجرا `python3 main.py` است. جزئیات کامل نصب، ساخت محیط مجازی، اجرای اسکرپر و محل خروجی‌ها در README آمده است.
"""
    output_path.write_text(content, encoding="utf-8")
